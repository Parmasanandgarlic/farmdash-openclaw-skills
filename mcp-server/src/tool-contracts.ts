export enum ToolAuthority {
  FARMDASH_READ_ONLY = 'FARMDASH_READ_ONLY',
  FARMDASH_ANALYZES = 'FARMDASH_ANALYZES',
  FARMDASH_PREPARES = 'FARMDASH_PREPARES',
  /**
   * FarmDash performs an authenticated, durable, server-side state mutation
   * after verifying caller authority and evidence. It never acquires custody,
   * never signs, and never broadcasts. Distinct from FARMDASH_PREPARES (which
   * returns material only) and from every user/provider authority (where the
   * move leaves FarmDash's hands).
   */
  FARMDASH_WRITES = 'FARMDASH_WRITES',
  USER_SIGNS = 'USER_SIGNS',
  USER_SUBMITS = 'USER_SUBMITS',
  DELEGATED_SIGNER = 'DELEGATED_SIGNER',
  PROVIDER_EXECUTES = 'PROVIDER_EXECUTES',
  OPERATOR_ONLY = 'OPERATOR_ONLY',
}

export enum FinancialEffect {
  NONE = 'NONE',
  QUOTED_ONLY = 'QUOTED_ONLY',
  PREPARATION_ONLY = 'PREPARATION_ONLY',
  CUSTOMER_SIGNED_SPEND = 'CUSTOMER_SIGNED_SPEND',
  PROVIDER_FEE = 'PROVIDER_FEE',
  API_PAYMENT = 'API_PAYMENT',
  REVENUE_OBSERVATION = 'REVENUE_OBSERVATION',
}

export enum EvidenceClass {
  OBSERVED = 'OBSERVED',
  DERIVED = 'DERIVED',
  EDITORIAL = 'EDITORIAL',
  STALE = 'STALE',
  UNAVAILABLE = 'UNAVAILABLE',
  CALLER_ASSERTED = 'CALLER_ASSERTED',
  PROVIDER_VERIFIED = 'PROVIDER_VERIFIED',
  /** Cryptographic signature verification (EIP-191/EIP-712) WITHOUT chain settlement. */
  SIGNATURE_VERIFIED = 'SIGNATURE_VERIFIED',
  /** Evidence actually established from chain state (transaction hashes, receipts). */
  ONCHAIN_VERIFIED = 'ONCHAIN_VERIFIED',
}

// --- Tool contract shape ---

export interface ToolContract {
  toolName: string;
  /** HTTP-only compatibility contracts must never inflate MCP discovery. */
  mcpRegistered: boolean;
  /** Conservative selection hint; backend authentication remains authoritative. */
  readOnly: boolean;
  destructive: boolean;
  /** Explicit replay answer for SESSION_BOUND contracts; never inferred from mutation. */
  sessionBoundIdempotent?: boolean;
  apiRoute: string;
  featureStatusId: string;
  capabilityFamily: string;
  integrationRoles: string[];
  availability: string;
  tier: string;
  mockSupported?: boolean;
  authority: ToolAuthority;
  financialEffect: FinancialEffect;
  inputArtifacts: string[];
  outputArtifacts: string[];
  prerequisites: string[];
  freshnessRequirements: string;
  userConfirmationRequirement: boolean;
  executionDomain?: 'futures' | 'selectable';
  executionModeRequirements?: Record<'USER_SIGNED' | 'BOUNDED_AUTONOMOUS', { userConfirmationRequirement: boolean; walletSignatureRequirement: boolean; status: string; prerequisites: string[] }>;
  walletSignatureRequirement: boolean;
  /**
   * Who submits the signed action to the venue.
   * - 'USER'     the caller submits after signing.
   * - 'FARMDASH' FarmDash forwards an action the user already signed (e.g. a Hyperliquid
   *              L1 action) and returns the venue response. FarmDash never signs and
   *              never holds keys.
   */
  submissionOwner: 'USER' | 'PROVIDER' | 'OPERATOR' | 'NONE' | 'FARMDASH';
  idempotencySemantics: 'IDEMPOTENT' | 'NOT_IDEMPOTENT' | 'SESSION_BOUND';
  nextTools: string[];
  blockedAlternatives: string[];
  evidenceClasses: EvidenceClass[];
  commercialModel: string;
}

