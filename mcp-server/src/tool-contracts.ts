// --- Helpers ---

export function getToolContract(name: string): ToolContract {
  const contract = TOOL_CONTRACTS[name];
  if (!contract) throw new Error(`Missing tool contract for ${name}`);
  return contract;
}

export function getMcpToolNames(): string[] {
  return Object.values(TOOL_CONTRACTS)
    .filter(contract => contract.mcpRegistered)
    .map(contract => contract.toolName)
    .sort();
}

export function getToolAnnotations(name: string) {
  const contract = getToolContract(name);
  if (typeof contract.readOnly !== 'boolean' || typeof contract.destructive !== 'boolean') {
    throw new Error(`Missing canonical safety annotations for ${name}`);
  }
  if (contract.idempotencySemantics === 'SESSION_BOUND'
    && typeof contract.sessionBoundIdempotent !== 'boolean') {
    throw new Error(`Missing explicit session-bound idempotency for ${name}`);
  }
  return {
    title: `FarmDash ${contract.toolName}`,
    readOnlyHint: contract.readOnly,
    destructiveHint: contract.destructive,
    idempotentHint: contract.idempotencySemantics === 'IDEMPOTENT'
      || (contract.idempotencySemantics === 'SESSION_BOUND' && contract.sessionBoundIdempotent === true),
    openWorldHint: true,
  };
}

export function getContractByFamily(family: string): ToolContract[] {
  return Object.values(TOOL_CONTRACTS).filter(c => c.capabilityFamily === family);
}

export function getAllToolNames(): string[] {
  return Object.keys(TOOL_CONTRACTS);
}

export function getContractCount(): number {
  return Object.keys(TOOL_CONTRACTS).length;
}
